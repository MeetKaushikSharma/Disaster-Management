export function getDistrictsForStates(stateNames: string[]): { state: string; districts: string[] }[] {
  return stateNames
    .map((name) => {
      const stateObj = INDIA_STATES.find(
        (s) =>
          s.name === name ||
          (name === 'Delhi' && s.code === 'DL') ||
          (name === 'Andaman and Nicobar Islands' && s.code === 'AN')
      );
      return stateObj ? { state: stateObj.name, districts: stateObj.districts } : null;
    })
    .filter((item): item is { state: string; districts: string[] } => item !== null);
}

export function getAllDistrictsForState(stateName: string): string[] {
  const stateObj = INDIA_STATES.find(
    (s) =>
      s.name === stateName ||
      (stateName === 'Delhi' && s.code === 'DL') ||
      (stateName === 'Andaman and Nicobar Islands' && s.code === 'AN')
  );
  return stateObj ? stateObj.districts : [];
}

export function findStateForDistrict(districtName: string, selectedStates: string[]): string | undefined {
  for (const sName of selectedStates) {
    const stateObj = INDIA_STATES.find(
      (s) =>
        s.name === sName ||
        (sName === 'Delhi' && s.code === 'DL') ||
        (sName === 'Andaman and Nicobar Islands' && s.code === 'AN')
    );
    if (stateObj && stateObj.districts.includes(districtName)) {
      return stateObj.name;
    }
  }
  return undefined;
}
